-- supabase.sql – 교육 신청 현황 관리 표 만들기
-- Supabase 대시보드 > SQL Editor에 전체를 붙여 넣고 Run 한다.
-- 여러 번 실행해도 안전하다. (이미 있으면 건너뜀)

-- 과정별 정원
create table if not exists public.edu_courses (
  course   text primary key,
  capacity int  not null default 5 check (capacity between 1 and 100)
);

-- 교육 신청
create table if not exists public.edu_apps (
  id         bigint generated by default as identity primary key,
  course     text not null,
  date       date not null,
  hours      int  not null check (hours > 0),
  name       text not null,
  team       text not null,
  status     text not null default '신청' check (status in ('신청', '이수', '취소')),
  created_at timestamptz not null default now()
);

-- 브라우저(anon)에서 쓸 수 있도록 권한 부여
grant select, insert, update on public.edu_courses to anon, authenticated;
grant select, insert, update on public.edu_apps    to anon, authenticated;

-- RLS 켜기
alter table public.edu_courses enable row level security;
alter table public.edu_apps    enable row level security;

-- 시연용 정책 : 누구나 읽기·추가·수정 가능 (삭제는 허용하지 않음)
drop policy if exists "demo read"   on public.edu_courses;
drop policy if exists "demo insert" on public.edu_courses;
drop policy if exists "demo update" on public.edu_courses;
create policy "demo read"   on public.edu_courses for select to anon, authenticated using (true);
create policy "demo insert" on public.edu_courses for insert to anon, authenticated with check (true);
create policy "demo update" on public.edu_courses for update to anon, authenticated using (true) with check (true);

drop policy if exists "demo read"   on public.edu_apps;
drop policy if exists "demo insert" on public.edu_apps;
drop policy if exists "demo update" on public.edu_apps;
create policy "demo read"   on public.edu_apps for select to anon, authenticated using (true);
create policy "demo insert" on public.edu_apps for insert to anon, authenticated with check (true);
create policy "demo update" on public.edu_apps for update to anon, authenticated using (true) with check (true);

-- 가상 데이터 : 과정 3개 (정원 5명)
insert into public.edu_courses (course, capacity) values
  ('정보보안 기본', 5),
  ('생성형 AI 실무', 5),
  ('보고서 작성 기초', 5)
on conflict (course) do nothing;

-- 가상 데이터 : 신청 8건 (표가 비어 있을 때만 넣음)
insert into public.edu_apps (course, date, hours, name, team, status, created_at)
select v.course, v.date::date, v.hours, v.name, v.team, v.status, now() - (10 - v.n) * interval '1 minute'
from (values
  (1, '정보보안 기본',    '2026-09-24', 3, '김가상', '기획팀', '이수'),
  (2, '정보보안 기본',    '2026-09-24', 3, '이가상', '안전팀', '이수'),
  (3, '정보보안 기본',    '2026-09-24', 3, '박가상', '운영팀', '취소'),
  (4, '생성형 AI 실무',   '2026-10-16', 7, '김가상', '기획팀', '신청'),
  (5, '생성형 AI 실무',   '2026-10-16', 7, '최가상', '안전팀', '신청'),
  (6, '생성형 AI 실무',   '2026-10-16', 7, '정가상', '운영팀', '신청'),
  (7, '생성형 AI 실무',   '2026-10-16', 7, '한가상', '기획팀', '신청'),
  (8, '보고서 작성 기초', '2026-11-05', 4, '오가상', '운영팀', '신청')
) as v(n, course, date, hours, name, team, status)
where not exists (select 1 from public.edu_apps);
